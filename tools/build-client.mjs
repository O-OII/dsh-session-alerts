/** Deterministic official loader factories; shared sidebar source, no SDK copying. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const sidebar = ['completion-contract.mjs','completion-reader.mjs','completed-filter.mjs','sidebar-messages.mjs','completed-sidebar.mjs'];
function source(name) {
  return readFileSync(new URL(name, root), 'utf8')
    .replace(/^import .+ from ['"][^'"]+['"];?\r?\n/gm, '')
    .replace(/^export /gm, '');
}
function bundle(id, names) {
  return `// Generated by tools/build-client.mjs from shared authored sources.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(id)},\n  factory: (require) => {\n    const { createElement, useEffect, useRef } = require('react');\n${names.map(source).join('\n')}\n    return { name, inject, apply };\n  },\n});\n`;
}
const normal = bundle('dsh-native-taskbar-badge', ['read-client.mjs', ...sidebar, 'client.mjs']);
const standalone = bundle('dsh-session-alerts-sidebar', [...sidebar, 'sidebar-client.mjs']);
const outputs = [['client.js',normal], ['sidebar-client.js',standalone], ['sidebar-package/client.js',standalone]];
for (const file of ['completion.mjs','completion-state.mjs','completion-contract.mjs','LICENSE']) outputs.push([`sidebar-package/${file}`,readFileSync(new URL(file,root),'utf8')]);
for (const language of ['en','zh']) {
  const meta = JSON.parse(readFileSync(new URL(`locale/${language}.json`,root),'utf8')).meta;
  outputs.push([`sidebar-package/locale/${language}.json`,JSON.stringify({meta:{title:meta.title,description:language==='zh'
    ? '已完成主会话侧栏筛选及只读完成投影；不启动Python或原生角标引擎。'
    : 'Completed-main-session sidebar and read-only completion projection; no Python or native badge engine.'}},null,2)+'\n']);
}
for (const [name, text] of outputs) {
  const output = new URL(name, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== text) throw new Error(`${name} is stale; run npm run build`);
  } else { mkdirSync(dirname(fileURLToPath(output)), { recursive: true }); writeFileSync(output, text); }
  console.log(`${process.argv.includes('--check') ? 'Verified' : 'Built'} ${fileURLToPath(output)}`);
}
