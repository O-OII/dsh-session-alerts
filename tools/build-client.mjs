/** Deterministic dependency-free official loader-factory build. No SDK copying. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
let driver = readFileSync(new URL('read-client.mjs', root), 'utf8').replaceAll('export ', '');
let client = readFileSync(new URL('client.mjs', root), 'utf8')
  .replace("import { createElement, useEffect, useRef } from 'react';", "const { createElement, useEffect, useRef } = require('react');")
  .replace("import { createReadReceipt } from './read-client.mjs';\n", '').replaceAll('export ', '');
const result = `// Generated by tools/build-client.mjs; edit client.mjs/read-client.mjs instead.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-native-taskbar-badge',\n  factory: (require) => {\n${driver}\n${client}\n    return { name, inject, apply };\n  },\n});\n`;
const output = new URL('client.js', root);
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== result) throw new Error('client.js is stale; run node tools/build-client.mjs');
} else writeFileSync(output, result);
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Built'} ${fileURLToPath(output)}`);
